// Official social channels, verified to exist (opened Nov 3 2026). Add a channel here only after its profile page
// loads under this exact address. YouTube (@GoFlipForge) is not listed: that address returned "404 Not Found".
export const SOCIAL = [
  { label: 'Instagram', mark: 'IG', handle: '@goflipforge', href: 'https://www.instagram.com/goflipforge/', id: 'instagram' },
  { label: 'TikTok', mark: 'TT', handle: '@goflipforge', href: 'https://www.tiktok.com/@goflipforge', id: 'tiktok' }
];
export const CONNECT_HREF = '/connect/';
// Pages whose footer carries the generated "Follow FlipForge" column (every header page plus the Connect page tiles).
const SOCIAL_START = '<!-- ff:site-social — generated by scripts/site-header.mjs; edit SOCIAL there, not here -->';
const SOCIAL_END = '<!-- /ff:site-social -->';
const esc = value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function renderFooterSocial() {
  const links = SOCIAL.map(item => `<a href="${esc(item.href)}" target="_blank" rel="noopener noreferrer me" aria-label="${esc(item.label)} ${esc(item.handle)} (opens in a new tab)">${esc(item.label)} <span class="footer-handle">${esc(item.handle)}</span></a>`).join('');
  return `${SOCIAL_START}<div class="footer-links footer-social"><strong>Follow FlipForge</strong>${links}<a href="${CONNECT_HREF}" data-ff-connect-entry>All channels &amp; contact</a></div>${SOCIAL_END}`;
}

export function renderConnectTiles() {
  const tiles = SOCIAL.map(item => [
    `          <a class="ff-social-link" href="${esc(item.href)}" target="_blank" rel="noopener noreferrer me" data-ff-connect-link="${esc(item.id)}">`,
    `            <span class="ff-social-mark" aria-hidden="true">${esc(item.mark)}</span>`,
    `            <span><strong>${esc(item.label)}</strong><small>${esc(item.handle)}</small></span>`,
    '            <b aria-hidden="true">↗</b>',
    '          </a>'
  ].join('\n')).join('\n\n');
  return `${SOCIAL_START}\n${tiles}\n          ${SOCIAL_END}`;
}

const SOCIAL_BLOCK = new RegExp(`${SOCIAL_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${SOCIAL_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);

// Writes the "Follow FlipForge" column at the end of the page footer's link columns.
export function applyFooterSocial(file, html) {
  const block = renderFooterSocial();
  if (SOCIAL_BLOCK.test(html)) return html.replace(SOCIAL_BLOCK, block);
  const footerAt = html.search(/<footer class="(?:footer|ff-proof-footer)"/);
  if (footerAt < 0) throw new Error(`${file}: no site footer found`);
  // Standard footer: the link columns end right before the copyright line. Decision Proof: right before </footer>.
  const endMarker = html.indexOf('<div class="copyright"', footerAt) >= 0 && html.indexOf('<div class="copyright"', footerAt) < html.indexOf('</footer>', footerAt)
    ? html.indexOf('<div class="copyright"', footerAt)
    : html.indexOf('</footer>', footerAt);
  const closeAt = html.lastIndexOf('</div>', endMarker);
  if (closeAt < footerAt) throw new Error(`${file}: footer link columns not found`);
  return html.slice(0, closeAt) + block + html.slice(closeAt);
}

export function applyConnectTiles(html) {
  const block = renderConnectTiles();
  if (SOCIAL_BLOCK.test(html)) return html.replace(SOCIAL_BLOCK, block);
  const grid = /(<div class="ff-connect-social-grid">\n)[\s\S]*?(\n\s*<\/div>\n\s*<\/section>)/;
  if (!grid.test(html)) throw new Error('connect/index.html: social grid not found');
  return html.replace(grid, (_, open, close) => `${open}          ${block}${close}`);
}

const START = '<!-- ff:site-header — generated by scripts/site-header.mjs; edit the list there, not here -->';
const END = '<!-- /ff:site-header -->';

export function sectionsFor(file) {
  const home = file === 'index.html';
  return SECTIONS.filter(item => (home ? item.home : item.pages));
}

export function render(file) {
  const current = PAGES[file];
  const links = sectionsFor(file).map(item => {
    const attrs = [`href="${item.href}"`];
    if (item.audience) attrs.push('data-ff-audience-navigation');
    if (current && current === item.href) attrs.push('aria-current="page"');
    return `      <li><a ${attrs.join(' ')}>${item.label}</a></li>`;
  }).join('\n');
  return [
    START,
    '<header class="site-header">',
    '  <div class="nav">',
    `    <a class="brand" href="/" aria-label="FlipForge home"><img class="brand-lockup" src="assets/brand/flipforge-logo-horizontal.svg" alt="${LOCKUP_ALT}"></a>`,
    '    <div class="site-header-actions">',
    '      <a class="nav-cta" href="/beta-application.html">Request Beta Access</a>',
    '      <button class="menu-toggle" type="button" aria-expanded="false" aria-controls="site-menu"><span class="menu-toggle-icon" aria-hidden="true"></span><span class="menu-toggle-label">Menu</span></button>',
    '    </div>',
    '  </div>',
    '</header>',
    '<nav class="site-menu" id="site-menu" aria-label="Site menu">',
    '  <div class="site-menu-group">',
    '    <p class="site-menu-heading">Explore FlipForge</p>',
    '    <ul class="site-menu-links">',
    links,
    '    </ul>',
    '  </div>',
    '  <div class="site-menu-group site-menu-returning">',
    '    <p class="site-menu-heading" id="site-menu-beta-users">Existing beta users</p>',
    `    <a class="site-menu-sign-in" href="${BETA_SIGN_IN_HREF}" data-ff-marketing-sign-in aria-describedby="site-menu-beta-users">Beta Sign In</a>`,
    '  </div>',
    '  <a class="site-menu-cta" href="/beta-application.html">Request Beta Access</a>',
    '</nav>',
    '<div class="backdrop" aria-hidden="true"></div>',
    END
  ].join('\n');
}

// The block a page carries today: the generated block, or (once, on first conversion) the earlier hand-written header,
// its mobile menu and backdrop.
const GENERATED = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
const LEGACY = /<header class="site-header"[\s\S]*?<div class="backdrop"[^>]*><\/div>/;

export function apply(file, html) {
  const block = render(file);
  if (GENERATED.test(html)) return html.replace(GENERATED, block);
  if (LEGACY.test(html)) return html.replace(LEGACY, block);
  throw new Error(`${file}: no site header found`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  const problems = [];
  for (const file of Object.keys(PAGES)) {
    const full = path.join(root, file);
    const html = fs.readFileSync(full, 'utf8');
    const count = (html.match(/<header class="site-header"/g) || []).length;
    if (count !== 1) problems.push(`${file}: expected one site header, found ${count}`);
    let next;
    try { next = applyFooterSocial(file, apply(file, html)); } catch (error) { problems.push(error.message); continue; }
    if ((next.match(/ff:site-social —/g) || []).length !== 1) problems.push(`${file}: expected one Follow FlipForge footer column`);
    if (next === html) continue;
    if (write) fs.writeFileSync(full, next);
    else problems.push(`${file}: header differs from scripts/site-header.mjs (run: node scripts/site-header.mjs --write)`);
  }
  // The Connect page's channel tiles come from the same SOCIAL list.
  {
    const full = path.join(root, 'connect/index.html');
    const html = fs.readFileSync(full, 'utf8');
    let next = html;
    try { next = applyConnectTiles(html); } catch (error) { problems.push(error.message); }
    if (next !== html) {
      if (write) fs.writeFileSync(full, next);
      else problems.push('connect/index.html: channel tiles differ from scripts/site-header.mjs (run: node scripts/site-header.mjs --write)');
    }
  }
  // No other file may build, inject or relabel the header menu or the footer links.
  const forbidden = [
    ['assets/js/conversion-events.js', /renderPrimaryNav|canonicalPrimaryNav|homePrimaryNav/],
    ['assets/js/site.js', /ensureReturningBetaSignIn|querySelectorAll\('\.desktop-nav'\)/],
    ['scripts/build-assets.js', /ensureDesktopAppLink|ensureMobileAppLink|ensureFooterAppLink/]
  ];
  for (const [file, pattern] of forbidden) {
    if (pattern.test(fs.readFileSync(path.join(root, file), 'utf8'))) problems.push(`${file}: must not build or rewrite the site header`);
  }
  if (problems.length) {
    console.error(problems.map(p => `::error title=site-header::${p}`).join('\n'));
    process.exit(1);
  }
  console.log(write ? 'Site header and Follow FlipForge footer column written to every public page; Connect tiles written.' : `Site header and Follow FlipForge column match scripts/site-header.mjs on ${Object.keys(PAGES).length} pages and the Connect page; no other file builds them.`);
}
