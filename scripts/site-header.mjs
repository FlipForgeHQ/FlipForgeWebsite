// The one source of the public website header and menu.
//
// Every public page carries the same header in its HTML, written by this script from the list below. Nothing rewrites
// the header after it is written: no runtime menu builders, no build-time link injection. To change the menu, edit
// this file and run `node scripts/site-header.mjs --write`; CI and the Netlify build run `--check`, which fails when
// any page's header differs from what this file produces.
//
// Layout: logo on the left; Request Beta Access and a labeled "Menu" button on the right, at every width. The menu
// lists the site sections, then an "Existing beta users" group with Beta Sign In, then Request Beta Access.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const BETA_SIGN_IN_HREF = '/production-auth.html?return=%2Fapp%2Fbeta%2F%23%2Fbeta-start';
export const LOCKUP_ALT = 'FlipForge — Card Decision Intelligence — Before you buy. Know Why.';

// Site sections, in menu order. `home` and `pages` choose where each appears.
export const SECTIONS = [
  { label: 'Product', href: '/product.html', home: true, pages: true },
  { label: 'Who It’s For', href: '#who-its-for', home: true, pages: false, audience: true },
  { label: 'Decision Intelligence', href: '/decision-intelligence.html', home: true, pages: true },
  { label: 'Evidence Lab', href: '/learn.html', home: true, pages: true },
  { label: 'Launch Plans', href: '/pricing.html', home: false, pages: true },
  { label: 'About', href: '/about.html', home: true, pages: true }
];

// Public pages that carry the shared header (file name → the section it represents, for aria-current).
export const PAGES = {
  'index.html': null,
  '404.html': null,
  'about.html': '/about.html',
  'beta-application.html': null,
  'beta-onboarding.html': null,
  'beta-terms.html': null,
  'data-use.html': null,
  'decision-intelligence.html': '/decision-intelligence.html',
  'decision-proof.html': null,
  'faq.html': null,
  'learn.html': '/learn.html',
  'price-is-not-proof.html': null,
  'pricing.html': '/pricing.html',
  'privacy.html': null,
  'product.html': '/product.html',
  'refund.html': null,
  'sample-decision-dossier.html': null,
  'terms.html': null,
  'thank-you.html': null
};

const START = '<!-- ff:site-header — generated by scripts/site-header.mjs; edit the list there, not here -->';
const END = '<!-- /ff:site-header -->';

export function sectionsFor(file) {
  const home = file === 'index.html';
  return SECTIONS.filter(item => (home ? item.home : item.pages));
}

export function render(file) {
  const current = PAGES[file];
  const links = sectionsFor(file).map(item => {
    const attrs = [`href="${item.href}"`];
    if (item.audience) attrs.push('data-ff-audience-navigation');
    if (current && current === item.href) attrs.push('aria-current="page"');
    return `      <li><a ${attrs.join(' ')}>${item.label}</a></li>`;
  }).join('\n');
  return [
    START,
    '<header class="site-header">',
    '  <div class="nav">',
    `    <a class="brand" href="/" aria-label="FlipForge home"><img class="brand-lockup" src="assets/brand/flipforge-logo-horizontal.svg" alt="${LOCKUP_ALT}"></a>`,
    '    <div class="site-header-actions">',
    '      <a class="nav-cta" href="/beta-application.html">Request Beta Access</a>',
    '      <button class="menu-toggle" type="button" aria-expanded="false" aria-controls="site-menu"><span class="menu-toggle-icon" aria-hidden="true"></span><span class="menu-toggle-label">Menu</span></button>',
    '    </div>',
    '  </div>',
    '</header>',
    '<nav class="site-menu" id="site-menu" aria-label="Site menu">',
    '  <div class="site-menu-group">',
    '    <p class="site-menu-heading">Explore FlipForge</p>',
    '    <ul class="site-menu-links">',
    links,
    '    </ul>',
    '  </div>',
    '  <div class="site-menu-group site-menu-returning">',
    '    <p class="site-menu-heading" id="site-menu-beta-users">Existing beta users</p>',
    `    <a class="site-menu-sign-in" href="${BETA_SIGN_IN_HREF}" data-ff-marketing-sign-in aria-describedby="site-menu-beta-users">Beta Sign In</a>`,
    '  </div>',
    '  <a class="site-menu-cta" href="/beta-application.html">Request Beta Access</a>',
    '</nav>',
    '<div class="backdrop" aria-hidden="true"></div>',
    END
  ].join('\n');
}

// The block a page carries today: the generated block, or (once, on first conversion) the earlier hand-written header,
// its mobile menu and backdrop.
const GENERATED = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
const LEGACY = /<header class="site-header"[\s\S]*?<div class="backdrop"[^>]*><\/div>/;

export function apply(file, html) {
  const block = render(file);
  if (GENERATED.test(html)) return html.replace(GENERATED, block);
  if (LEGACY.test(html)) return html.replace(LEGACY, block);
  throw new Error(`${file}: no site header found`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write');
  const problems = [];
  for (const file of Object.keys(PAGES)) {
    const full = path.join(root, file);
    const html = fs.readFileSync(full, 'utf8');
    const count = (html.match(/<header class="site-header"/g) || []).length;
    if (count !== 1) problems.push(`${file}: expected one site header, found ${count}`);
    let next;
    try { next = apply(file, html); } catch (error) { problems.push(error.message); continue; }
    if (next === html) continue;
    if (write) fs.writeFileSync(full, next);
    else problems.push(`${file}: header differs from scripts/site-header.mjs (run: node scripts/site-header.mjs --write)`);
  }
  // No other file may build, inject or relabel the header menu.
  const forbidden = [
    ['assets/js/conversion-events.js', /renderPrimaryNav|canonicalPrimaryNav|homePrimaryNav/],
    ['assets/js/site.js', /ensureReturningBetaSignIn|querySelectorAll\('\.desktop-nav'\)/],
    ['scripts/build-assets.js', /ensureDesktopAppLink|ensureMobileAppLink/]
  ];
  for (const [file, pattern] of forbidden) {
    if (pattern.test(fs.readFileSync(path.join(root, file), 'utf8'))) problems.push(`${file}: must not build or rewrite the site header`);
  }
  if (problems.length) {
    console.error(problems.map(p => `::error title=site-header::${p}`).join('\n'));
    process.exit(1);
  }
  console.log(write ? 'Site header written to every public page.' : `Site header matches scripts/site-header.mjs on ${Object.keys(PAGES).length} pages; no other file builds it.`);
}
