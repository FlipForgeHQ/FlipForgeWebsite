import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = relative => fs.readFileSync(path.join(root, relative), "utf8");
const exists = relative => fs.existsSync(path.join(root, relative));

const packageJson = JSON.parse(read("package.json"));
const netlify = read("netlify.toml");
const identity = read("scripts/lib/flipforge-identity-client.mjs");
const probe = read("scripts/lib/flipforge-staging-auth-probe.mjs");
const authPage = read("staging-auth.html");
const appIndex = read("saas-prototype/index.html");
const account = read("saas-prototype/account-lifecycle.js");
const accountCss = read("saas-prototype/account-lifecycle.css");
const documentation = read("docs/SAAS_CUSTOMER_ACCOUNT_LIFECYCLE.md");

const checks = [];
const check = (name, condition) => checks.push({ name, passed: Boolean(condition) });

check("001 account lifecycle validator is registered", packageJson.scripts?.["validate:account-lifecycle"] === "node scripts/validate-saas-customer-account-lifecycle.mjs");
check("002 Netlify build runs account lifecycle validation", netlify.includes("npm run validate:account-lifecycle"));
check("003 account lifecycle adapter exists", exists("saas-prototype/account-lifecycle.js"));
check("004 account lifecycle styles exist", exists("saas-prototype/account-lifecycle.css"));
check("005 account lifecycle documentation exists", exists("docs/SAAS_CUSTOMER_ACCOUNT_LIFECYCLE.md"));
check("006 Identity client imports password recovery", identity.includes("requestPasswordRecovery"));
check("007 Identity client imports self-service user updates", identity.includes("updateUser"));
check("008 public signup remains absent", !identity.includes("signup("));
check("009 invite acceptance remains supported", identity.includes("acceptInvite(state.inviteToken, password)"));
check("010 recovery callback opens password completion", identity.includes('callback?.type === "recovery"') && identity.includes("state.recoveryMode = true"));
check("011 password recovery completes through Identity", identity.includes("await updateUser({ password })"));
check("012 recovery token is removed from the address bar", identity.includes("clearCallbackHash()"));
check("013 recovery requests return a non-enumerating response", identity.includes("If that invited account exists, a password-recovery email has been sent."));
check("014 profile updates are self-service metadata only", identity.includes("updateUser({ data: { full_name: normalizedName } })"));
check("015 profile name is bounded", identity.includes("normalizedName.length > 120"));
check("016 Identity publishes a sanitized session snapshot", identity.includes("function identitySnapshot") && identity.includes('authenticated: true'));
check("017 session snapshot exposes membership booleans", identity.includes("membershipActive") && identity.includes("membershipConfigured"));
check("018 session snapshot does not return a tenant identifier field", !/return Object\.freeze\(\{[\s\S]{0,500}tenantId\s*:/m.test(identity));
check("019 Identity change event is published", identity.includes('new CustomEvent("flipforge:identity-change"'));
check("020 account adapter is deploy-preview constrained", account.includes("PREVIEW_HOST") && account.includes("eligibleHost()"));
check("021 account route reads only sanitized Identity snapshot", account.includes("getSnapshot") && !account.includes("getUser("));
check("022 account route never reads Identity roles", !/appMetadata|app_metadata|\.roles\b/.test(account));
check("023 account route has invitation-only boundary", account.includes("Invitation-only Identity"));
check("024 account route marks billing disconnected", account.includes('metric("Billing", "Not connected"'));
check("025 account route marks production inactive", account.includes('metric("Production", "Inactive"'));
check("026 account route never infers paid entitlements", account.includes("Capabilities are not inferred from the browser"));
check("027 provider administration remains excluded", account.includes("Provider administration") && account.includes("Excluded"));
check("028 transaction execution remains excluded", account.includes("No bid, purchase, checkout, payment, listing, or resale action exists."));
check("029 account profile edit uses Identity API", account.includes("api.updateProfile"));
check("030 account sign-out uses Identity API", account.includes("api.signOut"));
check("031 account recovery uses generic Identity API", account.includes("api.requestRecovery"));
check("032 isolated sign-in page includes recovery control", authPage.includes("data-staging-auth-recovery"));
check("033 isolated sign-in page includes safe return control", authPage.includes("data-staging-auth-return"));
check("034 isolated probe rejects cross-origin return targets", probe.includes("resolved.origin !== window.location.origin"));
check("035 isolated probe restricts return to SaaS prototype", probe.includes('resolved.pathname !== "/saas-prototype/"'));
check("036 isolated probe uses generic recovery response", probe.includes("If that invited account exists"));
check("037 app loads account lifecycle stylesheet", appIndex.includes('href="account-lifecycle.css"'));
check("038 app loads account lifecycle adapter", appIndex.includes('src="account-lifecycle.js"'));
check("039 account styles include responsive layout", accountCss.includes("@media(max-width:980px)"));
check("040 docs retain Smart Opportunity authority", documentation.includes("Smart Opportunity"));
check("041 docs retain existing PSA authority", documentation.includes("Existing PSA intelligence"));
check("042 docs prohibit public signup", documentation.includes("Public signup remains disabled"));
check("043 docs prohibit billing activation", documentation.includes("Billing and paid entitlement authority remain unavailable"));
check("044 docs prohibit production activation", documentation.includes("Production customer activation remains unavailable"));
check("045 no customer credential field was added", !/API key|service token input|provider password/i.test(account));

const failures = checks.filter(item => !item.passed);
console.log("SaaSCustomerAccountLifecycleValidation");
console.log(`PASSED: ${checks.length - failures.length}`);
console.log(`FAILED: ${failures.length}`);
for (const failure of failures) console.error(`FAIL | ${failure.name}`);
if (failures.length) process.exitCode = 1;
