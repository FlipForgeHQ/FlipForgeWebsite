import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const page = read('decision-intelligence.html');
const exhibitJs = read('assets/js/decision-intelligence-exhibit-v1.js');
const product = read('product.html');
const connect = read('connect/index.html');
const conversion = read('assets/js/conversion-events.js');
const customerShell = read('saas-prototype/customer-only-shell-v1.js');
const sitemap = read('sitemap.xml');

const checks = [];
const check = (name, condition) => checks.push({ name, passed: Boolean(condition) });
const sectionCount = text => (text.match(/<section\b/g) || []).length;
const publicText = page.replace(/<script[\s\S]*?<\/script>/gi, '').replace(/<style[\s\S]*?<\/style>/gi, '');
const forbiddenImplementationLanguage = /\b(?:API|SQLite|CardSight|Netlify|Render|JavaScript|source code|database|engineVersion|correlationId|provider credential|service credential)\b/i;
const exhibitContract = `${page}\n${exhibitJs}`;

check('dedicated Decision Intelligence page exists', page.includes('<title>What Is Decision Intelligence? | FlipForge</title>'));
check('current Card Decision Intelligence descriptor is used', page.includes('CARD DECISION INTELLIGENCE'));
check('current shared brand stylesheet is used', page.includes('assets/css/brand-v2.css'));
check('public exhibit visual system is loaded', page.includes('assets/css/decision-intelligence-exhibit-v1.css'));
check('public exhibit interaction is loaded', page.includes('assets/js/decision-intelligence-exhibit-v1.js'));
check('exhibit thesis is explicit', page.includes('See the evidence become the decision.'));
check('interactive exhibit exists', page.includes('data-ff-di-exhibit') && page.includes('Run the exhibit'));
check('five customer-facing reasoning stages are present', ['Identity','Evidence','Value','Decision','Outcome'].every(label => page.includes(`>${label}</button>`) || page.includes(` ${label}</button>`)));
check('exact identity remains explicit', page.includes('Exact card'));
check('evidence rejection is demonstrated', page.includes('7</strong><span>found') && page.includes('5</strong><span>rejected') && page.includes('2</strong><span>usable'));
check('apparent-versus-supported shift is demonstrated', exhibitContract.includes('24%') && exhibitContract.includes('2.3%'));
check('BUY WATCH VERIFY PASS language is explicit', /BUY, WATCH, VERIFY or PASS/.test(page));
check('no-transaction independence is explicit', page.includes('No transaction required.'));
check('outcome accountability is explicit', page.includes('Day 7') && page.includes('Day 14') && page.includes('Day 30'));
check('public exhibit protects proprietary methods', page.includes("does not publish its proprietary weighting, formulas, thresholds or internal methods"));
check('public page exposes no implementation vocabulary', !forbiddenImplementationLanguage.test(publicText));
check('exhibit automation supports reduced motion', exhibitJs.includes('prefers-reduced-motion'));
check('exhibit has direct user-controlled stages', exhibitJs.includes('data-ff-di-stage') && exhibitJs.includes('addEventListener("click"'));
check('Decision Intelligence page stays focused', sectionCount(page) <= 5);
check('Product page stays compact', sectionCount(product) <= 5);
check('Product uses current Card Decision Intelligence branding', product.includes('CARD DECISION INTELLIGENCE') && product.includes('Card Decision Intelligence'));
check('Decision Intelligence page is included in sitemap', sitemap.includes('https://goflipforge.com/decision-intelligence.html'));
check('Connect hub exposes Decision Intelligence', connect.includes('What is Decision Intelligence?') && connect.includes('/decision-intelligence.html'));
check('public navigation receives Decision Intelligence link', conversion.includes("link.textContent='Decision Intelligence'") && conversion.includes("link.href='/decision-intelligence.html'"));
check('Decision Intelligence click tracking is wired', conversion.includes('decision_intelligence_clicked'));
check('customer app exposes public Decision Intelligence exhibit', customerShell.includes('data.ffPublicDecisionIntelligence') || customerShell.includes('data-ff-public-decision-intelligence') || customerShell.includes('ffPublicDecisionIntelligence'));
check('customer app points public Decision Intelligence to the public page', customerShell.includes('publicLink.href = "/decision-intelligence.html"'));
check('private saved-data view is distinctly labeled', customerShell.includes('replaceTextNode(privateLink, "Saved Intelligence")'));

const passed = checks.filter(item => item.passed).length;
const failed = checks.filter(item => !item.passed);
console.log('FlipForge Decision Intelligence Public Exhibit Assurance');
console.log(`PASSED: ${passed}`);
console.log(`FAILED: ${failed.length}`);
for (const item of failed) console.error(`FAIL | ${item.name}`);
if (failed.length) process.exit(1);
