// Homepage hero governance, v10. File retained under its established workflow path.
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('index.html'),css=read('assets/css/homepage-v10.css'),js=read('assets/js/homepage-v10.js');
const sw=read('sw.js'),site=read('assets/js/site.js');
const out=[];
const check=(label,ok)=>out.push({label,ok});
const has=(s,t)=>s.includes(t);
const at=t=>html.indexOf(t);
check('exactly one H1',(html.match(/<h1\b/g)||[]).length===1);
check('single decision demo',(html.match(/data-ffdemo\b/g)||[]).length===1&&!has(html,'data-decision-forge'));
check('demo directly follows the hero',at('data-ff10-hero')<at('data-ffdemo')&&at('data-ffdemo')<at('id="how-it-works"'));
check('premium official palette',has(css,'#D4AF37')&&has(css,'#B8860B')&&has(css,'#8B8F98'));
check('Geist typography',has(css,'Geist'));
check('no retired slab art or stock photography',!has(html,'ff-fictional-slab-v1.svg')&&!has(html,'images.unsplash.com'));
check('invented card render, disclosed',has(html,'assets/images/ff10-hero.webp')&&has(html,'Invented for illustration; not a real card, player, set or grading company.'));
check('product-led hero without fabricated provider feeds',has(html,'class="ff10-panel"')&&!has(html,'data-provider-feed'));
check('visible example disclaimer',has(html,'<span class="ff10-chip">Illustrative</span>')&&has(html,'Fictional card and illustrative numbers. Not a live evaluation.')&&has(html,'NO REAL SALE DATA'));
check('explicit economics',has(html,'<span>Supported resale</span><b>$500</b>')&&has(html,'<span>Max Buy</span><b>$360</b>'));
check('no guaranteed profit',has(html,'NO GUARANTEED RETURN'));
check('range control and hint',has(html,'type="range"')&&has(html,'Drag the handle or use your arrow keys.'));
check('instant updates',has(js,"input.addEventListener('input', render)"));
check('two separate prices',has(html,'Asking price')&&has(html,'Max Buy'));
check('price gap',has(html,'Price gap')&&has(html,'data-price-gap-explain'));
check('decision quality guard',has(js,"if (unresolved) {")&&has(js,"verdict = 'VERIFY'"));
check('modeled costs and profit',has(js,'const profit = MODEL.resale - MODEL.fees - MODEL.shipping - ask;'));
check('hero panel mirrors the demo',has(js,"sync('verdict', r.verdict)")&&has(html,'data-ff10-sync="gap"'));
check('reset and reasoning',has(html,'data-reset')&&has(html,'How Max Buy is calculated'));
check('mobile usability',has(css,'@media(max-width:760px)')&&has(css,'.ff10-panel{position:relative'));
check('reduced motion',has(css,'@media(prefers-reduced-motion:reduce)'));
check('official logo',has(html,'flipforge-logo-horizontal.svg'));
check('paired header actions',has(html,'class="ffdemo-nav-actions"'));
check('no trading affordance',!/checkout|buy now|place bid|add to cart/i.test(html));
check('no network data',!/(fetch\s*\(|XMLHttpRequest)/.test(js));
check('only one major sales experience',!has(html,'data-film')&&!has(html,'data-decision-forge'));
const failed=out.filter(x=>!x.ok);
if(failed.length){failed.forEach(x=>console.error('FAIL: '+x.label));process.exit(1)}
console.log('PASS: '+out.length+' homepage hero v10 safety and experience checks.');
