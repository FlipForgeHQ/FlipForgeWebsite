import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDirectory, "..");
const read = relative => fs.readFileSync(path.join(root, relative), "utf8");

const index = read("saas-prototype/index.html");
const bulk = read("saas-prototype/bulk-evaluation.js");
const existing = read("saas-prototype/staging-evaluation.js");
const results = [];
const check = (name, condition) => results.push({ name, passed: Boolean(condition) });

check("001 bulk adapter is loaded", index.includes('src="bulk-evaluation.js"'));
check("002 bulk adapter loads after authoritative evaluation adapter", index.indexOf('src="staging-evaluation.js"') < index.indexOf('src="bulk-evaluation.js"'));
check("003 bulk limit is 25", bulk.includes("const MAX_ROWS = 25"));
check("004 fixed evaluation endpoint is reused", bulk.includes('const EVALUATION_PATH = "/api/v1/evaluations"') && bulk.includes("fetch(EVALUATION_PATH"));
check("005 no dynamic write endpoint", !/fetch\(\s*(?:path|url|endpoint)/.test(bulk));
check("006 POST only", bulk.includes('method: "POST"'));
check("007 same-origin credentials", bulk.includes('credentials: "same-origin"'));
check("008 cache disabled", bulk.includes('cache: "no-store"'));
check("009 redirects refused", bulk.includes('redirect: "error"'));
check("010 JSON UTF-8", bulk.includes('"Content-Type": "application/json; charset=utf-8"'));
check("011 correlation id sent", bulk.includes('"X-Correlation-Id": requestCorrelationId'));
check("012 idempotency key sent", bulk.includes('"Idempotency-Key": requestId'));
check("013 no browser tenant header", !/X-FlipForge-Tenant-Id/i.test(bulk));
check("014 no browser user header", !/X-FlipForge-User-Id/i.test(bulk));
check("015 no service token exposure", !/FLIPFORGE_API_SERVICE_TOKEN/.test(bulk));
check("016 no Authorization construction", !/Authorization/.test(bulk));
check("017 Smart Opportunity response authority required", bulk.includes('meta.authority === "Smart Opportunity"'));
check("018 existing PSA authority required", bulk.includes('meta.gradingAuthority === "Existing PSA intelligence"'));
check("019 SQLite persistence required", bulk.includes("data.persistedToSqlite === true"));
check("020 tenant ownership required", bulk.includes("data.tenantOwned === true"));
check("021 request cannot verify evidence", bulk.includes("data.requestCanVerifyEvidence === false"));
check("022 request cannot verify identity", bulk.includes("data.requestCanVerifyIdentity === false"));
check("023 no evidence acceptance", bulk.includes("data.evidenceAcceptedByRequest === false"));
check("024 no PSA recalculation", bulk.includes("data.psaRecalculated === false"));
check("025 no transaction authority", bulk.includes("data.transactionAuthorized === false"));
check("026 default-deny isolation required", bulk.includes('isolation.defaultAccess === "DENY"'));
check("027 tenant idempotency scope required", bulk.includes('isolation.idempotencyScope === "TENANT"'));
check("028 ownership grant on completion required", bulk.includes('isolation.opportunityOwnership === "GRANTED_ON_COMPLETION"'));
check("029 CSV parser handles quoted fields", bulk.includes("if (text[index + 1] === '\"')") && bulk.includes("CSV contains an unclosed quoted field"));
check("030 required CSV columns are enforced", ["externalListingId", "cardIdentity", "listingUrl", "itemPrice"].every(key => bulk.includes(`\"${key}\"`)));
check("031 marketplace defaults to EBAY", bulk.includes('marketplace: "EBAY"'));
check("032 same marketplace boundary is retained", ["EBAY", "COMC", "MYSLABS", "GOLDIN", "HERITAGE", "FANATICS_COLLECT", "DEALER", "CARD_SHOW", "FACEBOOK_GROUP", "OTHER"].every(value => bulk.includes(`\"${value}\"`)));
check("033 money uses integer cents", bulk.includes("BigInt(whole) * 100n"));
check("034 HTTP(S) listing URL required", bulk.includes('url.protocol === "http:"') && bulk.includes('url.protocol === "https:"'));
check("035 batch is sequential", bulk.includes("for (const row of state.rows)") && bulk.includes("await submitRow(row)"));
check("036 auth quota failures stop remaining rows", bulk.includes("error.status === 401") && bulk.includes("error.status === 403") && bulk.includes("error.status === 429") && bulk.includes("break;"));
check("037 explicit authority acknowledgement required", bulk.includes("state.acknowledged") && bulk.includes("does not authorize a purchase"));
check("038 template download exists", bulk.includes("flipforge-bulk-evaluate-template.csv"));
check("039 existing single evaluator remains present", existing.includes("function handleSubmit(form)") && existing.includes("submitEvaluation(payload, state.idempotencyKey)"));
check("040 bulk does not replace single evaluator", !bulk.includes("FlipForgeStagingEvaluationAdapter ="));

const failed = results.filter(result => !result.passed);
for (const result of results) console.log(`${result.passed ? "PASS" : "FAIL"} ${result.name}`);
console.log(`\nBulk evaluation validation: ${results.length - failed.length}/${results.length} passed.`);
if (failed.length) process.exitCode = 1;
