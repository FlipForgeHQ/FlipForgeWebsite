import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const read = name => fs.readFileSync(path.join(root, name), "utf8");

const index = read("index.html");
const loader = read("prototype-visual-loader.js");
const script = read("cockpit-expansion.js");
const styles = read("cockpit-expansion.css");
const layoutScript = read("cockpit-layout-fix.js");
const layoutStyles = read("cockpit-layout-fix.css");
const results = [];
const check = (name, condition) => results.push({ name, passed: Boolean(condition) });

check("001 cockpit stylesheet is loaded", index.includes('href="cockpit-expansion.css"'));
check("002 cockpit script is host-gated through the prototype loader", index.includes('src="prototype-visual-loader.js"') && loader.includes('"cockpit-expansion.js"'));
check("003 cockpit script loads after visual intelligence inside the loader", loader.indexOf('"cockpit-expansion.js"') > loader.indexOf('"visual-intelligence.js"'));
check("004 platform overview exists", script.includes("Every major FlipForge intelligence module"));
check("005 Evaluator module exists", script.includes('"Evaluator"'));
check("006 Smart Opportunity module exists", script.includes('"Smart Opportunity"'));
check("007 Trade Analyzer module exists", script.includes('"Trade Analyzer"'));
check("008 Grading Intelligence module exists", script.includes('"Grading Intelligence"'));
check("009 Deal Advisor module exists", script.includes('"Deal Advisor"'));
check("010 Portfolio Intelligence module exists", script.includes('"Portfolio Intelligence"'));
check("011 portfolio allocation visualization exists", script.includes("Portfolio by sport") && script.includes("cockpit-donut"));
check("012 condition data is not fabricated", script.includes("Condition distribution is not authoritative yet"));
check("013 evidence-state substitute is explicit", script.includes("shows saved evidence states instead of inventing condition facts"));
check("014 opportunity map exists", script.includes("Opportunity map") && script.includes("cockpit-map-point"));
check("015 opportunity map uses saved confidence and risk", script.includes("item.risk") && script.includes("item.confidence"));
check("016 trade preview excludes transaction authority", script.includes("cannot accept, send, execute, or authorize a trade"));
check("017 grading predictor uses existing PSA data", script.includes("core.psaAdvisor.scenarios"));
check("018 grade prediction boundary is explicit", script.includes("do not predict the grade of the specific raw card"));
check("019 quick evaluation entry exists", script.includes("Quick card evaluation"));
check("020 deal advisor uses saved top opportunity", script.includes("top.recommendation") && script.includes("top.reasons[0]"));
check("021 market intelligence exists", script.includes("Market intelligence") && script.includes("marketTrend"));
check("022 top opportunities exist", script.includes("Top opportunities") && script.includes("topOpportunityCards"));
check("023 market activity exists", script.includes("Market activity"));
check("024 recent alerts exist", script.includes("Recent alerts"));
check("025 no second recommendation score is introduced", !/ForgeScore|new recommendation engine/i.test(script));
check("026 no direct network access exists", !/\bfetch\s*\(|XMLHttpRequest|\bWebSocket\b/.test(`${script}\n${layoutScript}`));
check("027 no browser persistence exists", !/localStorage|sessionStorage|indexedDB/.test(`${script}\n${layoutScript}`));
check("028 no credentials exist", !/API_KEY|Authorization\s*:|Bearer\s+/i.test(`${script}\n${layoutScript}`));
check("029 desktop module grid exists", styles.includes("grid-template-columns: repeat(3"));
check("030 tablet breakpoint exists", styles.includes("@media (max-width: 1180px)"));
check("031 mobile breakpoint exists", styles.includes("@media (max-width: 700px)"));
check("032 narrow mobile breakpoint exists", styles.includes("@media (max-width: 480px)"));
check("033 reduced motion support exists", styles.includes("@media (prefers-reduced-motion: reduce)"));
check("034 chart meaning has accessible labels", script.includes('role="img"') && script.includes("aria-label"));
check("035 cockpit hierarchy stylesheet is loaded", index.includes('href="cockpit-layout-fix.css"'));
check("036 cockpit hierarchy script is loaded", index.includes('src="cockpit-layout-fix.js"'));
check("037 hierarchy fix loads after prototype visual loader", index.indexOf('src="cockpit-layout-fix.js"') > index.indexOf('src="prototype-visual-loader.js"'));
check("038 cockpit becomes the primary dashboard", layoutScript.includes("heading.after(cockpit)"));
check("039 deep analysis follows the cockpit", layoutScript.includes("deepAnalysisHeading.after(visualLayer)"));
